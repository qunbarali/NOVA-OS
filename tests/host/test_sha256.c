#include <assert.h>
#include <string.h>
#include "nova/sha256.h"
int main(void){
    static const uint8_t expected[32]={0xBA,0x78,0x16,0xBF,0x8F,0x01,0xCF,0xEA,0x41,0x41,0x40,0xDE,0x5D,0xAE,0x22,0x23,0xB0,0x03,0x61,0xA3,0x96,0x17,0x7A,0x9C,0xB4,0x10,0xFF,0x61,0xF2,0x00,0x15,0xAD};
    nova_sha256_t ctx;uint8_t digest[32];
    nova_sha256_init(&ctx);nova_sha256_update(&ctx,"a",1u);nova_sha256_update(&ctx,"bc",2u);nova_sha256_final(&ctx,digest);
    assert(memcmp(digest,expected,sizeof(expected))==0);
    nova_sha256_init(&ctx);nova_sha256_update(&ctx,"",0u);nova_sha256_final(&ctx,digest);
    return 0;
}
