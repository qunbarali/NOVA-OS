#include <assert.h>
#include <string.h>
#include "nova/sha256.h"
int main(void){
    static const uint8_t expected_abc[32]={0xBA,0x78,0x16,0xBF,0x8F,0x01,0xCF,0xEA,0x41,0x41,0x40,0xDE,0x5D,0xAE,0x22,0x23,0xB0,0x03,0x61,0xA3,0x96,0x17,0x7A,0x9C,0xB4,0x10,0xFF,0x61,0xF2,0x00,0x15,0xAD};
    static const uint8_t expected_empty[32]={0xE3,0xB0,0xC4,0x42,0x98,0xFC,0x1C,0x14,0x9A,0xFB,0xF4,0xC8,0x99,0x6F,0xB9,0x24,0x27,0xAE,0x41,0xE4,0x64,0x9B,0x93,0x4C,0xA4,0x95,0x99,0x1B,0x78,0x52,0xB8,0x55};
    nova_sha256_t ctx;uint8_t digest[32];
    nova_sha256_init(&ctx);nova_sha256_update(&ctx,"a",1u);nova_sha256_update(&ctx,"bc",2u);nova_sha256_final(&ctx,digest);
    assert(memcmp(digest,expected_abc,sizeof(expected_abc))==0);
    nova_sha256_init(&ctx);nova_sha256_update(&ctx,"",0u);nova_sha256_final(&ctx,digest);
    assert(memcmp(digest,expected_empty,sizeof(expected_empty))==0);
    return 0;
}
